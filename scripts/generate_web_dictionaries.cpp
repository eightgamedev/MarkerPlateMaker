#include "marker_plate.h"

#include <cstdint>
#include <iomanip>
#include <iostream>

int main() {
    std::cout << "// Generated by scripts/generate_web_dictionaries.cpp; do not edit.\n";
    for (const auto& dictionary : markerplate::supportedDictionaries()) {
        std::cout << "// " << dictionary.name << '\n';
        for (int id = 0; id < dictionary.markerCount; ++id) {
            std::uint64_t code = 0;
            const auto cells = markerplate::blackCellsForId(dictionary.type, id);
            for (std::size_t i = 0; i < cells.size(); ++i) {
                code |= static_cast<std::uint64_t>(cells[i]) << i;
            }
            std::cout << "0x" << std::hex << std::setw(13) << std::setfill('0') << code << "ULL,\n";
        }
    }
}
